"""Per-request wrappers for MCP tools with server-owned invocation context.

The model sees only the business arguments.  The wrapper derives the internal
invocation envelope from ``RunnableConfig`` immediately before dispatching the
underlying MCP tool, so ownership and correlation data cannot be supplied by a
tool call generated by the model.
"""

from __future__ import annotations

from collections.abc import Callable, Mapping
from typing import Any, Literal, Union
import uuid

from langchain_core.messages import ToolMessage
from langchain_core.runnables import RunnableConfig
from langchain_core.tools import BaseTool, StructuredTool
from pydantic import BaseModel, ConfigDict, Field, create_model


EnvelopeFactory = Callable[[RunnableConfig], Mapping[str, Any]]


def _resolve_json_schema(schema: Mapping[str, Any], root: Mapping[str, Any]) -> Mapping[str, Any]:
    """Resolve the local ``$ref`` form emitted by MCP JSON schemas."""

    reference = schema.get("$ref")
    if not isinstance(reference, str):
        return schema
    if not reference.startswith("#/"):
        raise ValueError(f"unsupported non-local JSON Schema reference: {reference!r}")

    resolved: Any = root
    for raw_part in reference[2:].split("/"):
        part = raw_part.replace("~1", "/").replace("~0", "~")
        if not isinstance(resolved, Mapping) or part not in resolved:
            raise ValueError(f"unresolvable JSON Schema reference: {reference!r}")
        resolved = resolved[part]
    if not isinstance(resolved, Mapping):
        raise ValueError(f"JSON Schema reference is not an object: {reference!r}")
    return resolved


def _json_schema_annotation(schema: Mapping[str, Any], root: Mapping[str, Any]) -> Any:
    """Translate the modest JSON Schema subset used by MCP tool arguments."""

    schema = _resolve_json_schema(schema, root)
    variants = schema.get("anyOf") or schema.get("oneOf")
    if isinstance(variants, list) and variants:
        annotations = tuple(
            _json_schema_annotation(variant, root)
            for variant in variants
            if isinstance(variant, Mapping)
        )
        if not annotations:
            return Any
        if len(annotations) == 1:
            return annotations[0]
        return Union[annotations]  # type: ignore[arg-type]

    enum_values = schema.get("enum")
    if isinstance(enum_values, list) and enum_values:
        return Literal.__getitem__(tuple(enum_values))

    schema_type = schema.get("type")
    if isinstance(schema_type, list):
        annotations = tuple(
            _json_schema_annotation({**schema, "type": item}, root)
            for item in schema_type
        )
        return Union[annotations]  # type: ignore[arg-type]
    if schema_type == "string":
        return str
    if schema_type == "integer":
        return int
    if schema_type == "number":
        return float
    if schema_type == "boolean":
        return bool
    if schema_type == "array":
        items = schema.get("items", {})
        item_type = (
            _json_schema_annotation(items, root)
            if isinstance(items, Mapping)
            else Any
        )
        return list[item_type]
    if schema_type == "object" or "properties" in schema:
        return dict[str, Any]
    if schema_type == "null":
        return type(None)
    return Any


def _public_json_args_schema(
    tool: BaseTool,
    schema: Mapping[str, Any],
    internal_field: str,
) -> type[BaseModel]:
    properties = schema.get("properties")
    if not isinstance(properties, Mapping):
        raise TypeError(f"MCP tool {tool.name!r} must expose an object args_schema")
    if internal_field not in properties:
        raise ValueError(
            f"MCP tool {tool.name!r} does not declare internal field {internal_field!r}"
        )

    required_value = schema.get("required", [])
    required = set(required_value) if isinstance(required_value, list) else set()
    public_fields: dict[str, tuple[Any, Any]] = {}
    for name, raw_field_schema in properties.items():
        if name == internal_field:
            continue
        if not isinstance(name, str) or not isinstance(raw_field_schema, Mapping):
            raise TypeError(f"MCP tool {tool.name!r} has an invalid JSON args_schema")

        annotation = _json_schema_annotation(raw_field_schema, schema)
        if name in required:
            default: Any = ...
        elif "default" in raw_field_schema:
            default = raw_field_schema["default"]
        else:
            annotation = Union[annotation, type(None)]
            default = None
        public_fields[name] = (
            annotation,
            Field(
                default=default,
                title=raw_field_schema.get("title"),
                description=raw_field_schema.get("description"),
            ),
        )

    model_name = "".join(part.title() for part in tool.name.split("_")) + "PublicArgs"
    return create_model(
        model_name,
        __config__=ConfigDict(extra="forbid"),
        **public_fields,
    )


def _public_args_schema(tool: BaseTool, internal_field: str) -> type[BaseModel]:
    schema = tool.args_schema
    if isinstance(schema, Mapping):
        return _public_json_args_schema(tool, schema, internal_field)
    if not isinstance(schema, type) or not issubclass(schema, BaseModel):
        raise TypeError(
            f"MCP tool {tool.name!r} must expose a Pydantic or JSON Schema args_schema"
        )
    if internal_field not in schema.model_fields:
        raise ValueError(
            f"MCP tool {tool.name!r} does not declare internal field {internal_field!r}"
        )

    public_fields: dict[str, tuple[Any, Any]] = {}
    for name, field in schema.model_fields.items():
        if name == internal_field:
            continue
        public_fields[name] = (field.annotation, field)
    return create_model(f"{schema.__name__}Public", **public_fields)


def wrap_scoped_mcp_tool(
    tool: BaseTool,
    envelope_factory: EnvelopeFactory,
    *,
    internal_field: str = "invocation_envelope",
) -> StructuredTool:
    """Hide an MCP-only argument and inject it from trusted run configuration.

    The returned tool preserves the original name and description so it can
    replace the raw MCP tool in an Agent tool list without prompt changes.
    """

    public_schema = _public_args_schema(tool, internal_field)
    response_format = getattr(tool, "response_format", "content")

    async def call_scoped(config: RunnableConfig, **business_args: Any) -> Any:
        envelope = dict(envelope_factory(config))
        if not envelope:
            raise ValueError("trusted invocation envelope is required")
        scoped_args = {**business_args, internal_field: envelope}
        if response_format == "content_and_artifact":
            # A plain dict invocation returns only the already-formatted content
            # from BaseTool, which would make this wrapper return a list where
            # StructuredTool expects the original ``(content, artifact)`` pair.
            # ToolCall form preserves both values on a ToolMessage so the outer
            # wrapper can expose the same response contract safely.
            result = await tool.ainvoke(
                {
                    "type": "tool_call",
                    "name": tool.name,
                    "id": f"scoped-{uuid.uuid4().hex}",
                    "args": scoped_args,
                },
                config=config,
            )
            if not isinstance(result, ToolMessage):
                raise TypeError(
                    f"MCP tool {tool.name!r} did not preserve content and artifact"
                )
            return result.content, result.artifact
        return await tool.ainvoke(scoped_args, config=config)

    return StructuredTool.from_function(
        coroutine=call_scoped,
        name=tool.name,
        description=tool.description or f"Scoped wrapper for {tool.name}",
        args_schema=public_schema,
        infer_schema=False,
        response_format=response_format,
    )


def wrap_signed_mcp_tool(tool: BaseTool, *, internal_field: str = "invocation_envelope"):
    from agent.invocation_context import envelope_from_config

    return wrap_scoped_mcp_tool(
        tool,
        lambda config: envelope_from_config(config, tool.name),
        internal_field=internal_field,
    )
